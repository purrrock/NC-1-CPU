#ifndef NC1_CORE_H
#define NC1_CORE_H

#include <stdint.h>
#include <stdbool.h>

/*
 * NC-1 CPU core
 *
 * Этот заголовочный файл описывает состояние процессора и публичный
 * интерфейс CPU core.
 *
 * Важно:
 *   - core не зависит от Windows;
 *   - core не зависит от STM32 HAL;
 *   - периферия и физическая память будут подключаться отдельным слоем;
 *   - регистры NC-1 хранятся в uint8_t, но архитектурно являются 4-битными.
 */

/* --------------------------------------------------------------------------
 * Register file
 * -------------------------------------------------------------------------- */

/*
 * NC-1 имеет восемь архитектурных регистров:
 *
 *   0  A
 *   1  B
 *   2  X
 *   3  Y
 *   4  SP
 *   5  FL
 *   6  PCH
 *   7  PCL
 *
 * Значения регистров ограничены младшими четырьмя битами.
 */
typedef enum
{
    NC1_REG_A   = 0,
    NC1_REG_B   = 1,
    NC1_REG_X   = 2,
    NC1_REG_Y   = 3,
    NC1_REG_SP  = 4,
    NC1_REG_FL  = 5,
    NC1_REG_PCH = 6,
    NC1_REG_PCL = 7
} nc1_reg_id_t;


/* --------------------------------------------------------------------------
 * Flags
 * -------------------------------------------------------------------------- */

/*
 * FL — 4-битный регистр флагов.
 *
 * По текущей архитектуре используются:
 *
 *   bit 0 — Z (Zero)
 *   bit 1 — C (Carry)
 *   bit 2 — M (Memory/Execution bank)
 *
 * Остальные биты пока не объявляем здесь как действующие флаги.
 */
#define NC1_FLAG_Z  (1u << 0)
#define NC1_FLAG_C  (1u << 1)
#define NC1_FLAG_M  (1u << 2)

#define NC1_NIBBLE_MASK  0x0Fu


/* --------------------------------------------------------------------------
 * CPU state
 * -------------------------------------------------------------------------- */

/*
 * Полное архитектурное состояние NC-1.
 *
 * regs[]:
 *     Регистры A..PCL.
 *
 * halted:
 *     Состояние остановки CPU.
 *
 * jumped_this_cycle:
 *     Внутреннее состояние, необходимое механизму выполнения инструкции:
 *     после перехода текущая инструкция не должна дополнительно изменять PC.
 *
 * Память и MMIO намеренно НЕ находятся внутри этой структуры.
 * Они будут предоставлены memory/platform layer.
 */
typedef struct
{
    uint8_t regs[8];

    bool halted;
    bool jumped_this_cycle;

} nc1_cpu_t;


/* --------------------------------------------------------------------------
 * CPU lifecycle
 * -------------------------------------------------------------------------- */

/*
 * Сбросить состояние CPU в начальное состояние.
 *
 * Реальная начальная конфигурация должна соответствовать спецификации
 * NC-1 и текущей эталонной реализации Python.
 */
void nc1_reset(nc1_cpu_t *cpu);


/* --------------------------------------------------------------------------
 * Register access
 * -------------------------------------------------------------------------- */

/*
 * Прочитать архитектурный регистр.
 *
 * Возвращаемое значение всегда находится в диапазоне 0..15.
 */
uint8_t nc1_get_reg(const nc1_cpu_t *cpu, nc1_reg_id_t reg);


/*
 * Записать значение в архитектурный регистр.
 *
 * Значение маскируется до 4 бит.
 */
void nc1_set_reg(nc1_cpu_t *cpu, nc1_reg_id_t reg, uint8_t value);


/* --------------------------------------------------------------------------
 * Flags
 * -------------------------------------------------------------------------- */

/*
 * Прочитать весь регистр FL.
 */
uint8_t nc1_get_flags(const nc1_cpu_t *cpu);


/*
 * Установить значение FL.
 *
 * Только архитектурно используемые младшие 4 бита сохраняются.
 */
void nc1_set_flags(nc1_cpu_t *cpu, uint8_t value);


/*
 * Проверить состояние отдельного флага.
 *
 * Возвращает true, если флаг установлен.
 */
bool nc1_flag_is_set(const nc1_cpu_t *cpu, uint8_t flag);


/*
 * Установить или сбросить отдельный флаг.
 */
void nc1_flag_set(nc1_cpu_t *cpu, uint8_t flag, bool state);


/* --------------------------------------------------------------------------
 * Program Counter
 * -------------------------------------------------------------------------- */

/*
 * Получить 8-битный PC из регистров PCH/PCL.
 *
 * PC архитектурно представлен двумя 4-битными регистрами:
 *
 *     PCH:PCL
 */
uint8_t nc1_get_pc(const nc1_cpu_t *cpu);


/*
 * Установить PC.
 *
 * Старшая тетрада записывается в PCH,
 * младшая — в PCL.
 */
void nc1_set_pc(nc1_cpu_t *cpu, uint8_t address);


/* --------------------------------------------------------------------------
 * Execution
 * -------------------------------------------------------------------------- */

/*
 * Выполнить одну инструкцию NC-1.
 *
 * Реализация декодирования и исполнения будет добавлена после того,
 * как базовое состояние CPU и memory layer будут готовы.
 */
void nc1_step(nc1_cpu_t *cpu);

#endif /* NC1_CORE_H */