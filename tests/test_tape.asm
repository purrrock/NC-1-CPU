; Тестовая программа: Потоковая I/O операция с накопителем
; Задача: Запись нибблов 0x0-0xF, последующее чтение в RAM по адресам 0x00-0x0F.
ORG 0x10

; --- 1. Открытие накопителя для записи ---
LDP 0xF9        ; X:Y = 0xF9 (указатель на контроллер накопителя STORAGE_CMD)
LDI 0x3         ; A = 3 (0b0011: MOTOR=1 [открытие], MODE=1 [режим записи])
STR             ; Передача команды в контроллер

LDI 0x1         
MOV B, A        ; Сохранение маски бита READY (0x1) во вспомогательный регистр B
WAIT_W_RDY:
LDR             ; Считывание статуса контроллера накопителя
AND B           ; Маскирование бита READY
JZR WAIT_W_RDY  ; Ожидание: если бит сброшен (Z=1), накопитель инициализируется

; --- 2. Потоковая запись последовательности 0x0 .. 0xF ---
LDI 0x0
MOV B, A        ; Сброс счетчика данных. Регистр B переиспользуется для цикла

WRITE_LOOP:
LDP 0xF8        ; Перенаправление X:Y на буфер потоковых данных STORAGE_DAT
MOV A, B        ; Загрузка генерируемого ниббла в аккумулятор
STR             ; Аппаратная запись в поток (контроллер сдвигает свой курсор автоматически)

INC A           ; Инкремент данных
MOV B, A        ; Сохранение обновленного значения
JCR WRITE_DONE  ; Переход при переполнении (C=1 возникает при инкременте 0xF -> 0x0)
JMP WRITE_LOOP   ; Безусловный относительный прыжок к следующей итерации записи

WRITE_DONE:
; --- 3. Закрытие файла ---
LDP 0xF9        ; X:Y = 0xF9 (STORAGE_CMD)
LDI 0x0         ; A = 0 (MOTOR=0, отключение мотора и сброс кеша на диск)
STR

; --- 4. Открытие файла на чтение ---
LDI 0x1         ; A = 1 (0b0001: MOTOR=1 [открытие], MODE=0 [режим чтения])
STR             ; Указатель X:Y все еще равен 0xF9, запись команды

LDI 0x1         
MOV B, A        ; Восстановление маски READY (0x1) в регистре B
WAIT_R_RDY:
LDR
AND B
JZR WAIT_R_RDY  ; Ожидание готовности контроллера к выдаче потока данных

; --- 5. Чтение данных из потока в память RAM (0x00 .. 0x0F) ---
LDI 0x0
MOV B, A        ; Регистр B теперь содержит смещение по адресам RAM (младший ниббл)

READ_LOOP:
LDP 0xF8        ; Возврат указателя X:Y на порт STORAGE_DAT
LDR             ; Мгновенное чтение очередного ниббла из файла в аккумулятор
PHA             ; Сохранение данных в аппаратный стек (для перенастройки указателя)

; Перенастройка косвенного указателя X:Y на целевую ячейку RAM
LDI 0x0
MOV X, A        ; X = 0 (старший ниббл адреса, страница Zero Page)
MOV A, B
MOV Y, A        ; Y = B (младший ниббл адреса, смещается от 0x0 до 0xF)

PLA             ; Извлечение прочитанного из накопителя ниббла обратно в аккумулятор
STR             ; Теневая запись (Shadow Write) напрямую в User RAM[0x00:Y]

MOV A, B        ; Извлечение счетчика адреса из B
INC A           ; Переход к следующей ячейке
MOV B, A
JCR READ_DONE   ; При переполнении (C=1) все 16 нибблов обработаны
JMP READ_LOOP    ; Относительный прыжок на следующую итерацию чтения

READ_DONE:
; --- 6. Завершение работы ---
LDP 0xF9        ; X:Y = 0xF9 (STORAGE_CMD)
LDI 0x0         
STR             ; Закрытие файла (MOTOR=0)

HLT             ; Аппаратная остановка процессора