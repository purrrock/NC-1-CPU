; Десятичный секундомер на 7-сегментных индикаторах (NC-1 v4.5)
; Обновление каждые 1.0 сек (4 тика таймера по 250 мс)
; Код не привязан к абсолютному адресу (Position-Independent)

; 1. Инициализация дисплеев (DISP_0 .. DISP_3 = 0)
INIT:
    LDP 0xF0        ; Установить указатель X:Y = 0xF0 (DISP_0)
    LDI 0x0         ; A = 0
    STR             ; RAM[0xF0] = 0 (Shadow Write аппаратно пишет в RAM)
    INX             ; X:Y = 0xF1
    STR             ; RAM[0xF1] = 0
    INX             ; X:Y = 0xF2
    STR             ; RAM[0xF2] = 0
    INX             ; X:Y = 0xF3
    STR             ; RAM[0xF3] = 0

; 2. Перезапуск секундного таймера
MAIN_LOOP:
    LDP 0xFA        ; Установить указатель на аппаратный таймер (MMIO 0xFA)
    LDI 0x4         ; 4 кванта * 250 мс = 1 секунда
    STR             ; Записать в 0xFA (запуск аппаратного отсчета)

; 3. Ожидание завершения отсчета (программный поллинг)
WAIT_TIMER:
    LDR             ; Считать текущее значение таймера в A
    DEC A           ; Вычитание из нуля (0x0 -> 0xF) установит флаг C=1
    JCR TICK_DONE   ; Если C=1 (таймер = 0), выйти из цикла поллинга
    JR WAIT_TIMER   ; Иначе (C=0) вернуться в начало цикла поллинга

; 4. Инкремент значения на индикаторах с десятичной коррекцией
TICK_DONE:
    LDP 0xF0        ; Установить указатель на младший разряд (DISP_0)

INC_LOOP:
    LDR             ; Считать текущую цифру разряда в A
    MOV B, A        ; Сохранить оригинальную цифру в B
    LDI 0x9         ; A = 9
    SUB B           ; A = 9 - B. Если оригинальная цифра была 9, результат 0 и Z=1
    JZR CARRY       ; Если Z=1 (цифра 9), перепрыгнуть к обработке переноса

    ; Иначе (цифра 0..8): инкремент и завершение
    MOV A, B        ; Восстановить оригинальную цифру из B обратно в A
    INC A           ; Увеличить на 1
    STR             ; Записать обратно в дисплей
    JMP MAIN_LOOP   ; Возврат к перезапуску таймера

; 5. Обработка десятичного переноса в следующий разряд
CARRY:
    LDI 0x0         ; A = 0
    STR             ; Обнулить текущий дисплей (9 -> 0)
    
NEXT_DIGIT:
    INX             ; Сдвинуть указатель на следующий дисплей (например, F0 -> F1)
    
    ; Защита от выхода за пределы дисплеев (проверка достижения адреса 0xF4)
    MOV A, Y        ; Скопировать младший ниббл адреса (Y) в аккумулятор
    MOV B, A        ; B = Y
    LDI 0x4         ; A = 4 (соответствует MMIO адресу KBD_STAT 0xF4)
    SUB B           ; A = 4 - Y. Если указатель достиг 4, результат 0 и Z=1
    JZR OVERFLOW    ; Если достигнут 0xF4 (Z=1), переполнение всех дисплеев
    JMP INC_LOOP    ; Иначе продолжить перенос (инкремент следующего разряда)

OVERFLOW:
    JMP MAIN_LOOP   ; Сброс секундомера 9999 -> 0000 (дисплеи уже обнулены каскадом CARRY)